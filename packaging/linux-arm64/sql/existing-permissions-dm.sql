-- Existing metadata: add the access column only when missing.
DECLARE
    v_count INTEGER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'DATA_SOURCE_ACCESS' AND COLUMN_NAME = 'PERMISSION_CODES';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE JDDBMS.DATA_SOURCE_ACCESS ADD PERMISSION_CODES VARCHAR(255) DEFAULT ''METADATA_READ,DATA_READ''';
    END IF;
END;
/
UPDATE JDDBMS.DATA_SOURCE_ACCESS
   SET PERMISSION_CODES = 'METADATA_READ,DATA_READ'
 WHERE PERMISSION_CODES IS NULL;
COMMIT;
