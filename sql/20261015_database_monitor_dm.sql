-- 在 JDDBMS 元数据库模式下执行一次；应用启动时也会自动补建缺失表。
CREATE TABLE DB_MONITOR_CONFIG (
    DATA_SOURCE_ID BIGINT PRIMARY KEY,
    ENABLED INT NOT NULL,
    ACTIVE_THRESHOLD INT NOT NULL,
    SPACE_THRESHOLD INT NOT NULL,
    USER_ID BIGINT NOT NULL,
    REVISION VARCHAR(36) NOT NULL
);
CREATE TABLE DB_MONITOR_SAMPLE (
    DATA_SOURCE_ID BIGINT NOT NULL,
    CAPTURED_AT BIGINT NOT NULL,
    SESSION_COUNT BIGINT,
    ACTIVE_COUNT BIGINT,
    BLOCKED_COUNT BIGINT,
    SPACE_PERCENT DECIMAL(7,2),
    ERROR_TEXT VARCHAR(1000),
    PRIMARY KEY (DATA_SOURCE_ID, CAPTURED_AT)
);
CREATE INDEX IDX_MON_SAMPLE_TIME ON DB_MONITOR_SAMPLE(CAPTURED_AT);
CREATE TABLE DB_MONITOR_ALERT (
    ID VARCHAR(36) PRIMARY KEY,
    DATA_SOURCE_ID BIGINT NOT NULL,
    ALERT_KEY VARCHAR(32) NOT NULL,
    STARTED_AT BIGINT NOT NULL,
    LAST_SEEN BIGINT NOT NULL,
    ENDED_AT BIGINT,
    MESSAGE VARCHAR(1000) NOT NULL
);
CREATE INDEX IDX_MON_ALERT_SOURCE ON DB_MONITOR_ALERT(DATA_SOURCE_ID, STARTED_AT);
CREATE INDEX IDX_MON_ALERT_END ON DB_MONITOR_ALERT(ENDED_AT);
