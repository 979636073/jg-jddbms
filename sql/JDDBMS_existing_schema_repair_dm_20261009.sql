-- JDDBMS existing metadata schema repair for the legacy data-source save path.
-- Run as JDDBMS on an existing database. Safe to run more than once.
-- Do not run the full initialization SQL on an existing database.

DECLARE
    v_count INTEGER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'DATA_SOURCE' AND COLUMN_NAME = 'PASSWORD_COPY';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE "JDDBMS"."DATA_SOURCE" ADD "PASSWORD_COPY" VARCHAR2(128)';
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'DATA_SOURCE' AND COLUMN_NAME = 'IS_SAVE';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE "JDDBMS"."DATA_SOURCE" ADD "IS_SAVE" BIT';
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_TABLES
     WHERE TABLE_NAME = 'HISTORY_USER_LOG';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE "JDDBMS"."HISTORY_USER_LOG" (' ||
          '"ID" BIGINT IDENTITY(1,1) NOT NULL, ' ||
          '"GMT_CREATE" DATETIME(6), "GMT_MODIFIED" DATETIME(6), ' ||
          '"USER_ID" INTEGER NOT NULL, "STATUS" TINYINT NOT NULL, ' ||
          '"DATA_SOURCE_ID" INTEGER NOT NULL, ' ||
          'NOT CLUSTER PRIMARY KEY("ID")) STORAGE(ON "MAIN", CLUSTERBTR)';
    END IF;

    SELECT COUNT(*) INTO v_count FROM USER_TABLES
     WHERE TABLE_NAME = 'PIGENHOLE';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE TABLE "JDDBMS"."PIGENHOLE" (' ||
          '"ID" BIGINT IDENTITY(1,1) NOT NULL, ' ||
          '"USER_NAME" VARCHAR2(50), "FILTER" VARCHAR2(2000), ' ||
          '"TABLES" VARCHAR2(2000), "UPDATE_TIME" DATE, ' ||
          '"TASK_NAME" VARCHAR2(50)) STORAGE(ON "MAIN", CLUSTERBTR)';
    END IF;
END;
/

-- All counts below must be 1. No user or data-source rows are modified.
SELECT 'DATA_SOURCE.PASSWORD_COPY' AS OBJECT_NAME, COUNT(*) AS FOUND
  FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'DATA_SOURCE' AND COLUMN_NAME = 'PASSWORD_COPY'
UNION ALL
SELECT 'DATA_SOURCE.IS_SAVE', COUNT(*)
  FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'DATA_SOURCE' AND COLUMN_NAME = 'IS_SAVE'
UNION ALL
SELECT 'HISTORY_USER_LOG', COUNT(*)
  FROM USER_TABLES WHERE TABLE_NAME = 'HISTORY_USER_LOG'
UNION ALL
SELECT 'PIGENHOLE', COUNT(*)
  FROM USER_TABLES WHERE TABLE_NAME = 'PIGENHOLE';

-- This query must return no rows. It checks every DATA_SOURCE column mapped by
-- DataSourceDO, not just the two legacy additions repaired above.
SELECT expected.COLUMN_NAME AS MISSING_DATA_SOURCE_COLUMN
  FROM (
    SELECT 'ID' AS COLUMN_NAME FROM DUAL UNION ALL
    SELECT 'GMT_CREATE' FROM DUAL UNION ALL
    SELECT 'GMT_MODIFIED' FROM DUAL UNION ALL
    SELECT 'ALIAS' FROM DUAL UNION ALL
    SELECT 'URL' FROM DUAL UNION ALL
    SELECT 'USER_NAME' FROM DUAL UNION ALL
    SELECT 'PASSWORD' FROM DUAL UNION ALL
    SELECT 'TYPE' FROM DUAL UNION ALL
    SELECT 'ENV_TYPE' FROM DUAL UNION ALL
    SELECT 'USER_ID' FROM DUAL UNION ALL
    SELECT 'HOST' FROM DUAL UNION ALL
    SELECT 'PORT' FROM DUAL UNION ALL
    SELECT 'SSH' FROM DUAL UNION ALL
    SELECT 'SSL' FROM DUAL UNION ALL
    SELECT 'SID' FROM DUAL UNION ALL
    SELECT 'DRIVER' FROM DUAL UNION ALL
    SELECT 'JDBC' FROM DUAL UNION ALL
    SELECT 'EXTEND_INFO' FROM DUAL UNION ALL
    SELECT 'DRIVER_CONFIG' FROM DUAL UNION ALL
    SELECT 'ENVIRONMENT_ID' FROM DUAL UNION ALL
    SELECT 'KIND' FROM DUAL UNION ALL
    SELECT 'SERVICE_NAME' FROM DUAL UNION ALL
    SELECT 'SERVICE_TYPE' FROM DUAL UNION ALL
    SELECT 'AUTHENTICATION_TYPE' FROM DUAL UNION ALL
    SELECT 'PASSWORD_COPY' FROM DUAL UNION ALL
    SELECT 'IS_SAVE' FROM DUAL
  ) expected
 WHERE NOT EXISTS (
    SELECT 1 FROM USER_TAB_COLUMNS actual
     WHERE actual.TABLE_NAME = 'DATA_SOURCE'
       AND actual.COLUMN_NAME = expected.COLUMN_NAME
 );

-- This query must also return no rows for the history write after save.
SELECT expected.COLUMN_NAME AS MISSING_HISTORY_COLUMN
  FROM (
    SELECT 'ID' AS COLUMN_NAME FROM DUAL UNION ALL
    SELECT 'GMT_CREATE' FROM DUAL UNION ALL
    SELECT 'GMT_MODIFIED' FROM DUAL UNION ALL
    SELECT 'USER_ID' FROM DUAL UNION ALL
    SELECT 'STATUS' FROM DUAL UNION ALL
    SELECT 'DATA_SOURCE_ID' FROM DUAL
  ) expected
 WHERE NOT EXISTS (
    SELECT 1 FROM USER_TAB_COLUMNS actual
     WHERE actual.TABLE_NAME = 'HISTORY_USER_LOG'
       AND actual.COLUMN_NAME = expected.COLUMN_NAME
 );
