 ON ((r.ROLE_ID IN (10,11,12) AND m.MENU_ID IN (3,2001))
  OR (r.ROLE_ID IN (10,11,13) AND m.MENU_ID IN (2,2002))
  OR (r.ROLE_ID=10 AND m.MENU_ID BETWEEN 2100 AND 2107)
  OR (r.ROLE_ID=11 AND m.MENU_ID IN (2100,2101,2105))
  OR (r.ROLE_ID=12 AND m.MENU_ID IN (2100,2107))
  OR (r.ROLE_ID=13 AND m.MENU_ID IN (2100,2105))
  OR (r.ROLE_ID=14 AND m.MENU_ID IN (2100,2107))
  OR (r.ROLE_ID=13 AND m.MENU_ID IN (108,500,501))
  OR (r.ROLE_ID=14 AND (m.MENU_ID IN (1,100,101,2,108,500,501,3,2001)
      OR m.PARENT_ID IN (100,101))))
 WHERE r.ROLE_ID IN (10,11,12,13,14)
 AND NOT EXISTS (SELECT 1 FROM JDDBMS.SYS_ROLE_MENU rm
                 WHERE rm.ROLE_ID=r.ROLE_ID AND rm.MENU_ID=m.MENU_ID);

