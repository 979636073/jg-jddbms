CREATE TABLE DB_MONITOR_ALERT (
    ID VARCHAR(36) PRIMARY KEY,
    DATA_SOURCE_ID BIGINT NOT NULL,
    ALERT_KEY VARCHAR(32) NOT NULL,
    STARTED_AT BIGINT NOT NULL,
    LAST_SEEN BIGINT NOT NULL,
    ENDED_AT BIGINT,
    MESSAGE VARCHAR(1000) NOT NULL
);
CREATE INDEX IDX_MON_ALERT_SOURCE ON DB_MONITOR_ALERT(DATA_SOURCE_ID, STARTED_AT);
CREATE INDEX IDX_MON_ALERT_END ON DB_MONITOR_ALERT(ENDED_AT);
