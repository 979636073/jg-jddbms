-- 仅限专用 Oracle QA 模式；创建前先确认 USER_OBJECTS 中 QR9_% 为 0。
CREATE TABLE QR9_PAGE AS
SELECT LEVEL AS ID, MOD(LEVEL, 7) AS BUCKET, RPAD('X', 200, 'X') AS NOTE
FROM DUAL CONNECT BY LEVEL <= 10001;

